// KeyVector lists the public keys derived from one mnemonic.
type KeyVector struct {
	Mnemonic      string `json:"mnemonic"`
	NostrPubkey   string `json:"nostr_pubkey"`
	Npub          string `json:"npub"`
	EVMAddress    string `json:"evm_address"`
	BTCAddress    string `json:"btc_address"`
	BTCEscrowXpub string `json:"btc_escrow_xpub"`
	Libp2pPeerID  string `json:"libp2p_peer_id"`
}

// File is the whole document.
type File struct {
	Comment  string               `json:"_comment"`
	Keys     map[string]KeyVector `json:"keys"`
	Order    map[string]any       `json:"order"`
	BTC      map[string]any       `json:"btc_escrow"`
	Safe     map[string]any       `json:"safe"`
	SafeTx   map[string]any       `json:"safe_tx"`
	Delivery map[string]any       `json:"delivery"`
	GiftWrap map[string]any       `json:"gift_wrap"`
}

